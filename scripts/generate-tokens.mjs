#!/usr/bin/env node
// Writes Aegis Terra's design tokens from design/tokens.json to the Apple app:
//   shield-apple/Shield/Assets.xcassets/<Name>.colorset   (one per `apple` name)
//   shield-apple/Shield/Design/Tokens.gen.swift           (radius, space, alpha, motion, type,
//                                                          severity / kind / hazard-type mappings)
// and fails when a pair in `contrastPairs` is under its minimum (WCAG 2.x contrast).
// The web outputs (tokens.css) arrive with the Phase 2 web client.
//
//   node scripts/generate-tokens.mjs           write
//   node scripts/generate-tokens.mjs --check   write nothing; exit 1 if anything is stale
//
// Pattern: apps/aaru/scripts/generate-tokens.mjs.
import { existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')
const t = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'))

const hex = (h) => {
  const m = /^#([0-9a-f]{6})$/i.exec(h)
  if (!m) throw new Error(`not a #rrggbb colour: ${h}`)
  const n = parseInt(m[1], 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}

// ---- colour lookup + contrast gate -------------------------------------------------------
const lookup = (name) => {
  const [group, key] = name.includes('.') ? name.split('.') : ['colors', name]
  const v = group === 'colors' ? t.colors[key]?.dark : t[group]?.[key]?.dark
  if (!v) throw new Error(`contrastPairs: unknown colour ${name}`)
  return v
}
const lum = (h) => {
  const c = hex(h).map((v) => v / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
}
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)]
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05)
}
const failures = t.contrastPairs
  .map((p) => ({ ...p, r: ratio(lookup(p.fg), lookup(p.bg)) }))
  .filter((p) => p.r < p.min)
if (failures.length) {
  for (const f of failures) console.error(`contrast: ${f.fg} on ${f.bg} is ${f.r.toFixed(2)}, needs ${f.min}`)
  process.exit(1)
}

// ---- outputs -------------------------------------------------------------------------------
const out = new Map() // path -> content

const assets = join(root, 'shield-apple/Shield/Assets.xcassets')
const colorset = (h) => {
  const [r, g, b] = hex(h)
  const c = (v) => '0x' + v.toString(16).toUpperCase().padStart(2, '0')
  return JSON.stringify(
    {
      colors: [
        {
          color: { 'color-space': 'srgb', components: { alpha: '1.000', blue: c(b), green: c(g), red: c(r) } },
          idiom: 'universal',
        },
      ],
      info: { author: 'generate-tokens.mjs', version: 1 },
    },
    null,
    2,
  ) + '\n'
}
const sets = [] // [appleName, hex]
for (const v of Object.values(t.colors)) for (const n of v.apple ?? []) sets.push([n, v.dark])
for (const v of Object.values(t.severity)) if (v.apple) for (const n of v.apple) sets.push([n, v.dark])
for (const v of Object.values(t.kind)) if (v.apple) for (const n of v.apple) sets.push([n, v.dark])
for (const [name, h] of sets) out.set(join(assets, `${name}.colorset/Contents.json`), colorset(h))

// Swift
const num = (n) => (Number.isInteger(n) ? `${n}` : `${n}`)
const camel = (s) => s.replace(/[-_](\w)/g, (_, c) => c.toUpperCase())
const sevKeys = ['minor', 'moderate', 'severe', 'extreme']
const swiftTypeCase = { tropical_cyclone: 'tropicalCyclone', heavy_rain: 'heavyRain', snow_ice: 'snowIce' }
const fontStyle = { largeTitle: '.largeTitle', title2: '.title2', headline: '.headline', subheadline: '.subheadline', footnote: '.footnote', caption2: '.caption2' }
const weight = { regular: '.regular', semibold: '.semibold', bold: '.bold', medium: '.medium' }

const lines = []
const L = (s = '') => lines.push(s)
L('// Generated by scripts/generate-tokens.mjs from design/tokens.json. Do not edit by hand:')
L('// change design/tokens.json and run `node scripts/generate-tokens.mjs`.')
L('// Colours are asset-catalog colour sets (Color.canvas, Color.panel, Color.severityMinor, ...).')
L()
L('import ShieldCore')
L('import SwiftUI')
L()
L('enum ShieldRadius {')
for (const [k, v] of Object.entries(t.radius)) if (!k.startsWith('$')) L(`    static let ${k}: CGFloat = ${num(v)}`)
L('}')
L()
L('/// The 4-pt grid. `s4` is 16 pt.')
L('enum ShieldSpace {')
for (const [k, v] of Object.entries(t.space)) if (!k.startsWith('$')) L(`    static let s${k}: CGFloat = ${num(v)}`)
L('}')
L()
L('enum ShieldAlpha {')
for (const [k, v] of Object.entries(t.alpha)) L(`    static let ${camel(k)}: Double = ${num(v)}`)
L('}')
L()
L('/// Motion (DESIGN.md §13). Callers fall back to a cross-fade under Reduce Motion.')
L('enum ShieldMotion {')
{
  const m = t.motion
  L(`    static let spring = Animation.spring(response: ${m.spring.response}, dampingFraction: ${m.spring.dampingFraction})`)
  for (const k of ['fast', 'standard', 'arrive']) {
    const e = m[k].easing === 'easeOut' ? 'easeOut' : m[k].easing === 'easeIn' ? 'easeIn' : 'easeInOut'
    L(`    static let ${k} = Animation.${e}(duration: ${m[k].ms / 1000})`)
  }
  L(`    static let extremePulseDuration: Double = ${m.extremePulse.ms / 1000}`)
}
L('}')
L()
L('/// Type scale (DESIGN.md §7). Built on text styles, so Dynamic Type applies.')
L('enum ShieldFont {')
for (const [k, v] of Object.entries(t.type.scale)) {
  let f = `Font${fontStyle[v.apple]}.weight(${weight[v.weight]})`
  if (v.digits === 'monospaced') f += '.monospacedDigit()'
  L(`    static let ${k}: Font = ${f}`)
}
L('}')
L()
L('enum ShieldTracking {')
for (const [k, v] of Object.entries(t.type.scale)) L(`    static let ${k}: CGFloat = ${num(v.tracking)}`)
L('}')
L()
L('/// The four marker shapes; severity is never colour alone (DESIGN.md §4).')
L('enum MarkerShapeKind: Sendable { case circle, diamond, triangle, octagon }')
L()
L('extension Severity {')
L('    var color: Color {')
L('        switch self {')
for (const k of sevKeys) L(`        case .${k}: .${camel(t.severity[k].apple[0].replace(/^./, (c) => c.toLowerCase()))}`)
L('        }')
L('    }')
L()
L('    var markerShape: MarkerShapeKind {')
L('        switch self {')
for (const k of sevKeys) L(`        case .${k}: .${t.severity[k].shape}`)
L('        }')
L('    }')
L()
L('    var markerScale: CGFloat {')
L('        switch self {')
for (const k of sevKeys) L(`        case .${k}: ${num(t.severity[k].markerScale)}`)
L('        }')
L('    }')
L()
L()
L('    /// The shape as a symbol, for badges and text-sized uses where a drawn octagon reads as a circle.')
L('    var sfSymbol: String {')
L('        switch self {')
for (const k of sevKeys) L(`        case .${k}: "${t.severity[k].sfSymbol}"`)
L('        }')
L('    }')
L()
L('    var pulses: Bool { self == .extreme }')
L('}')
L()
L('extension EventKind {')
L('    var sfSymbol: String {')
L('        switch self {')
for (const [k, v] of Object.entries(t.kind)) if (!k.startsWith('$')) L(`        case .${k}: "${v.sfSymbol}"`)
L('        }')
L('    }')
L('}')
L()
L('extension HazardType {')
L('    var sfSymbol: String {')
L('        switch self {')
for (const [k, v] of Object.entries(t.hazardType)) if (!k.startsWith('$')) L(`        case .${swiftTypeCase[k] ?? k}: "${v.sfSymbol}"`)
L('        }')
L('    }')
L('}')
out.set(join(root, 'shield-apple/Shield/Design/Tokens.gen.swift'), lines.join('\n') + '\n')

// ---- web (shield-app-web/apps/web) ------------------------------------------------------------
// Tailwind v4 reads `@theme` variables as utilities: `--color-canvas` gives `bg-canvas`, `text-canvas`.
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/_/g, '-').toLowerCase()
const px = (n) => `${n / 16}rem`
const css = []
const C = (s = '') => css.push(s)
C('/* Generated by scripts/generate-tokens.mjs from design/tokens.json. Do not edit by hand. */')
C('@theme {')
C('  --color-*: initial;')
for (const [k, v] of Object.entries(t.colors)) if (!k.startsWith('$') && v.dark) C(`  --color-${kebab(k)}: ${v.dark};`)
for (const k of sevKeys) C(`  --color-severity-${k}: ${t.severity[k].dark};`)
for (const [k, v] of Object.entries(t.kind)) if (!k.startsWith('$') && v.dark) C(`  --color-kind-${k}: ${v.dark};`)
// Increase Contrast swaps hairline for ink at alpha.hairlineStrong (DESIGN.md §14).
C(`  --color-hairline-strong: color-mix(in srgb, ${t.colors.ink.dark} ${Math.round(t.alpha.hairlineStrong * 100)}%, transparent);`)
C()
for (const [k, v] of Object.entries(t.radius)) if (!k.startsWith('$')) C(`  --radius-${k}: ${k === 'pill' ? '9999px' : px(v)};`)
C()
const shadow = (e) => {
  const hex = e.color.replace('#', '')
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16))
  return `0 ${e.y}px ${e.blur}px rgb(${r} ${g} ${b} / ${e.opacity})`
}
for (const [k, v] of Object.entries(t.elevation)) if (!k.startsWith('$')) C(`  --shadow-${kebab(k)}: ${shadow(v)};`)
C()
C('  --font-sans: -apple-system, BlinkMacSystemFont, "SF Pro Text", system-ui, "Segoe UI", Roboto, sans-serif;')
C('  --font-mono: ui-monospace, "SF Mono", SFMono-Regular, Menlo, Consolas, monospace;')
for (const [k, v] of Object.entries(t.type.scale)) {
  C(`  --text-${kebab(k)}: ${px(v.size)};`)
  C(`  --text-${kebab(k)}--letter-spacing: ${px(v.tracking)};`)
  C(`  --text-${kebab(k)}--font-weight: ${{ regular: 400, medium: 500, semibold: 600, bold: 700 }[v.weight]};`)
}
C()
C(`  --ease-shield: cubic-bezier(0.2, 0.8, 0.2, 1);`)
C(`  --animate-extreme-pulse: extreme-pulse ${t.motion.extremePulse.ms}ms ease-out infinite;`)
C('  @keyframes extreme-pulse {')
C('    0% { transform: scale(1); opacity: 0.45; }')
C('    100% { transform: scale(1.9); opacity: 0; }')
C('  }')
C('}')
C()
// Values that are not Tailwind theme namespaces: plain custom properties.
C(':root {')
for (const [k, v] of Object.entries(t.alpha)) if (!k.startsWith('$')) C(`  --alpha-${kebab(k)}: ${v};`)
for (const [k, v] of Object.entries(t.motion)) if (!k.startsWith('$') && v.ms) C(`  --motion-${kebab(k)}: ${v.ms}ms;`)
C(`  --motion-spring: ${Math.round(t.motion.spring.response * 1000)}ms;`)
C('}')
C()
// Translucency only where something floats over the map, never stacked (DESIGN.md §8).
C('@utility material-floating {')
for (const decl of t.material.floating.web.split(';').map((s) => s.trim()).filter(Boolean)) C(`  ${decl};`)
C('}')
out.set(join(root, 'shield-app-web/apps/web/src/styles/tokens.gen.css'), css.join('\n') + '\n')

const ts = []
const T = (s = '') => ts.push(s)
T('// Generated by scripts/generate-tokens.mjs from design/tokens.json. Do not edit by hand.')
T()
T('export const severityOrder = ["minor", "moderate", "severe", "extreme"] as const;')
T('export type SeverityKey = (typeof severityOrder)[number];')
T()
T('/** Shape, Lucide icon and label per severity: severity is never colour alone (DESIGN.md §4). */')
T('export const severityTokens = {')
const sevWebIcon = { circle: 'circle', diamond: 'diamond', triangle: 'triangle', octagon: 'octagon-alert' }
for (const k of sevKeys) {
  const s = t.severity[k]
  T(`  ${k}: { label: ${JSON.stringify(s.label)}, shape: ${JSON.stringify(s.shape)}, icon: ${JSON.stringify(sevWebIcon[s.shape])}, markerScale: ${s.markerScale}, pulses: ${Boolean(s.pulse)} },`)
}
T('} as const satisfies Record<SeverityKey, { label: string; shape: string; icon: string; markerScale: number; pulses: boolean }>;')
T()
T('/** Lucide icon and label per hazard type (DESIGN.md §6). */')
T('export const hazardTypeTokens = {')
for (const [k, v] of Object.entries(t.hazardType)) if (!k.startsWith('$')) T(`  ${k}: { label: ${JSON.stringify(v.label)}, icon: ${JSON.stringify(v.webIcon)} },`)
T('} as const;')
T('export type HazardTypeKey = keyof typeof hazardTypeTokens;')
T()
T('/** Fixed kind wording (DESIGN.md §2). */')
T('export const kindTokens = {')
for (const [k, v] of Object.entries(t.kind)) if (!k.startsWith('$')) T(`  ${k}: { label: ${JSON.stringify(v.label)} },`)
T('} as const;')
T()
T('/** Colours for canvas-drawn surfaces (MapLibre style, marker images) that cannot read CSS. */')
T('export const colorTokens = {')
for (const [k, v] of Object.entries(t.colors)) if (!k.startsWith('$') && v.dark) T(`  ${JSON.stringify(k)}: ${JSON.stringify(v.dark)},`)
T('} as const;')
T('export const severityColors = {')
for (const k of sevKeys) T(`  ${k}: ${JSON.stringify(t.severity[k].dark)},`)
T('} as const satisfies Record<SeverityKey, string>;')
T('export const kindColors = {')
for (const [k, v] of Object.entries(t.kind)) if (!k.startsWith('$') && v.dark) T(`  ${k}: ${JSON.stringify(v.dark)},`)
T('} as const;')
T()
T('/** Opacities (DESIGN.md §5, §8). */')
T('export const alphaTokens = {')
for (const [k, v] of Object.entries(t.alpha)) if (!k.startsWith('$')) T(`  ${k}: ${v},`)
T('} as const;')
T()
T('/** Shadows: offset y, blur radius, colour and opacity (DESIGN.md §8). */')
T('export const elevationTokens = {')
for (const [k, v] of Object.entries(t.elevation)) if (!k.startsWith('$')) T(`  ${k}: { y: ${v.y}, blur: ${v.blur}, color: ${JSON.stringify(v.color)}, opacity: ${v.opacity} },`)
T('} as const;')
T()
T('/** Durations in ms; the spring is response seconds and damping fraction (DESIGN.md §13). */')
T('export const motionTokens = {')
for (const [k, v] of Object.entries(t.motion)) if (!k.startsWith('$') && v.ms) T(`  ${k}: ${v.ms},`)
T(`  spring: { response: ${t.motion.spring.response}, dampingFraction: ${t.motion.spring.dampingFraction} },`)
T('} as const;')
out.set(join(root, 'shield-app-web/apps/web/src/design/tokens.gen.ts'), ts.join('\n') + '\n')

// ---- write or check -------------------------------------------------------------------------
let stale = []
for (const [p, content] of out) {
  const cur = existsSync(p) ? readFileSync(p, 'utf8') : null
  if (cur === content) continue
  stale.push(p.slice(root.length + 1))
  if (!check) {
    mkdirSync(dirname(p), { recursive: true })
    writeFileSync(p, content)
  }
}
// Colour sets this generator owns but no longer emits.
const wanted = new Set(sets.map(([n]) => `${n}.colorset`))
if (existsSync(assets)) {
  for (const d of readdirSync(assets)) {
    if (!d.endsWith('.colorset') || wanted.has(d)) continue
    const f = join(assets, d, 'Contents.json')
    if (existsSync(f) && readFileSync(f, 'utf8').includes('generate-tokens.mjs')) {
      stale.push(`shield-apple/Shield/Assets.xcassets/${d} (orphan)`)
      if (!check) rmSync(join(assets, d), { recursive: true })
    }
  }
}
if (check && stale.length) {
  console.error('Tokens are stale. Run `node scripts/generate-tokens.mjs`:\n  ' + stale.join('\n  '))
  process.exit(1)
}
console.log(check ? 'tokens up to date' : `wrote ${stale.length} file(s); ${t.contrastPairs.length} contrast pairs pass`)

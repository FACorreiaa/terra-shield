// Package aircraft serves the live flights layer (L1) from an in-memory
// cache in front of a quota-limited feed.
//
// The world is cut into fixed cells of CellDegrees, so every viewer of an
// area shares one cache entry and a client's bbox never reaches the feed.
// Each cell is fetched at most once per TTL (one request in flight per
// cell), and only while the feed's budget allows: the remaining quota it
// reports must stay above a reserve, a 429 stops all requests until its
// Retry-After, and a local pace spreads the daily quota over the day.
// When no request is allowed a cell is served stale, with its age, for up
// to MaxStale, then left out and the answer marked incomplete. Without a
// key (owner, 2026-11-19) the feed allows 500 requests a day: one request
// every 3.2 minutes for the whole server once the burst is spent. The
// defaults are sized from that (TestSteadyState): one viewer of a 4-cell
// view gets complete answers up to 12 minutes old. Clients show dataAt.
package aircraft

import (
	"context"
	"errors"
	"log/slog"
	"math"
	"sort"
	"sync"
	"time"

	"shield/internal/domain"
	"shield/internal/metrics"

	"golang.org/x/time/rate"
)

// CellDegrees is the cache grid. A 5° cell's farthest corner is 212 NM
// from its center at the equator, inside the feed's 250 NM circle.
const CellDegrees = 5.0

const (
	latCells = int(180 / CellDegrees)
	lonCells = int(360 / CellDegrees)
)

// Feed answers one circle. adsblol.Client is one.
type Feed interface {
	Area(ctx context.Context, lat, lon float64, radiusNM int) (domain.AircraftArea, error)
}

// Options tunes the cache. Zero values take the defaults.
type Options struct {
	TTL          time.Duration // a cell is not fetched again sooner; default 60 s
	MaxStale     time.Duration // a stale cell is served this long; default 15 min
	MaxCells     int           // cells one request may span; default 4
	Reserve      int           // feed quota kept back for other use; default 50
	PerDay       int           // local pace, requests a day; default 450
	Burst        int           // requests allowed at once under the pace; default 12
	ErrorBackoff time.Duration // a failed cell waits this long; default 30 s
	QuotaBackoff time.Duration // no requests this long at the reserve, or after a 429 without Retry-After; default 30 min
	FetchTimeout time.Duration // one feed request; default 8 s
	Now          func() time.Time
	Logger       *slog.Logger
	// Health records the feed's successes and failures under SourceID,
	// for /v1/sources. Optional.
	Health   Health
	SourceID string
}

// Health records a source's fetch results. store.SourceRepository is one.
type Health interface {
	RecordSuccess(ctx context.Context, id string, at time.Time, v domain.Validators) error
	RecordError(ctx context.Context, id string, at time.Time, msg string) error
}

func (o *Options) defaults() {
	set := func(d *time.Duration, v time.Duration) {
		if *d <= 0 {
			*d = v
		}
	}
	set(&o.TTL, time.Minute)
	set(&o.MaxStale, 15*time.Minute)
	set(&o.ErrorBackoff, 30*time.Second)
	set(&o.QuotaBackoff, 30*time.Minute)
	set(&o.FetchTimeout, 8*time.Second)
	for _, p := range []struct {
		n *int
		v int
	}{{&o.MaxCells, 4}, {&o.Reserve, 50}, {&o.PerDay, 450}, {&o.Burst, 12}} {
		if *p.n <= 0 {
			*p.n = p.v
		}
	}
	if o.Now == nil {
		o.Now = time.Now
	}
	if o.Logger == nil {
		o.Logger = slog.New(slog.DiscardHandler)
	}
}

// ErrTooLarge is a bbox spanning more than MaxCells cells.
var ErrTooLarge = errors.New("bbox spans too many cells")

// Result is the aircraft in a bbox.
type Result struct {
	Aircraft []domain.Aircraft
	// DataAt is when the oldest cell served was generated by the feed;
	// zero when nothing was served.
	DataAt time.Time
	// Complete is false when a cell had no data young enough to serve.
	Complete bool
}

type cellKey struct{ lat, lon int }

type cell struct {
	area      *domain.AircraftArea
	fetchedAt time.Time
	failedAt  time.Time
	inflight  chan struct{} // closed when the request in flight ends
}

// Service is safe for concurrent use.
type Service struct {
	feed    Feed
	o       Options
	limiter *rate.Limiter

	mu           sync.Mutex
	cells        map[cellKey]*cell
	blockedUntil time.Time
}

// New builds a Service on feed.
func New(feed Feed, o Options) *Service {
	o.defaults()
	return &Service{
		feed:    feed,
		o:       o,
		limiter: rate.NewLimiter(rate.Limit(float64(o.PerDay)/(24*60*60)), o.Burst),
		cells:   map[cellKey]*cell{},
	}
}

// TTL is how often a cell is refreshed at most.
func (s *Service) TTL() time.Duration { return s.o.TTL }

// MaxCells is how many cells one request may span.
func (s *Service) MaxCells() int { return s.o.MaxCells }

// InBox returns the aircraft inside bb.
func (s *Service) InBox(ctx context.Context, bb domain.BBox) (Result, error) {
	keys, err := cells(bb, s.o.MaxCells)
	if err != nil {
		return Result{}, err
	}
	areas := s.load(ctx, keys)

	res := Result{Complete: true}
	byHex := map[string]domain.Aircraft{}
	for _, a := range areas {
		if a == nil {
			res.Complete = false
			continue
		}
		if res.DataAt.IsZero() || a.At.Before(res.DataAt) {
			res.DataAt = a.At
		}
		for i := range a.Aircraft {
			ac := &a.Aircraft[i]
			if !inBox(bb, ac.Lon, ac.Lat) {
				continue
			}
			// Neighboring circles overlap: keep the newest fix.
			if held, ok := byHex[ac.Hex]; !ok || ac.PositionAt.After(held.PositionAt) {
				byHex[ac.Hex] = *ac
			}
		}
	}
	res.Aircraft = make([]domain.Aircraft, 0, len(byHex))
	for hex := range byHex {
		res.Aircraft = append(res.Aircraft, byHex[hex])
	}
	sort.Slice(res.Aircraft, func(i, j int) bool { return res.Aircraft[i].Hex < res.Aircraft[j].Hex })
	return res, nil
}

// load returns each cell's area (nil when none is young enough). Budget is
// claimed in one pass, stalest cell first, so a view's cells take turns
// when requests are scarce instead of racing for them; the claimed
// requests then run in parallel.
func (s *Service) load(ctx context.Context, keys []cellKey) []*domain.AircraftArea {
	areas := make([]*domain.AircraftArea, len(keys))
	fetch := make([]bool, len(keys))
	waits := make([]chan struct{}, len(keys))

	s.mu.Lock()
	now := s.o.Now()
	order := make([]int, len(keys))
	for i, k := range keys {
		order[i] = i
		if s.cells[k] == nil {
			s.cells[k] = &cell{}
		}
	}
	sort.SliceStable(order, func(a, b int) bool {
		return s.cells[keys[order[a]]].fetchedAt.Before(s.cells[keys[order[b]]].fetchedAt)
	})
	for _, i := range order {
		c := s.cells[keys[i]]
		switch {
		case c.inflight != nil:
			waits[i] = c.inflight
		case c.area != nil && now.Sub(c.fetchedAt) < s.o.TTL:
			metrics.AircraftCells.WithLabelValues("fresh").Inc()
			areas[i] = c.area
		case now.Sub(c.failedAt) >= s.o.ErrorBackoff && !now.Before(s.blockedUntil) && s.limiter.AllowN(now, 1):
			c.inflight = make(chan struct{})
			fetch[i] = true
		default:
			areas[i] = s.served(c, now)
		}
	}
	s.mu.Unlock()

	var wg sync.WaitGroup
	for i, k := range keys {
		if fetch[i] {
			wg.Go(func() { areas[i] = s.fetch(ctx, k) })
		}
	}
	wg.Wait()

	for i, ch := range waits {
		if ch == nil {
			continue
		}
		select {
		case <-ch:
		case <-ctx.Done():
		}
		s.mu.Lock()
		c := s.cells[keys[i]]
		if c.area != nil && s.o.Now().Sub(c.fetchedAt) < s.o.TTL {
			metrics.AircraftCells.WithLabelValues("fresh").Inc()
			areas[i] = c.area
		} else {
			areas[i] = s.served(c, s.o.Now())
		}
		s.mu.Unlock()
	}
	return areas
}

// fetch runs one claimed request (c.inflight is set) and records it.
func (s *Service) fetch(ctx context.Context, k cellKey) *domain.AircraftArea {
	// Detached: other viewers wait on this request, so one viewer leaving
	// must not cancel it (and waste the quota it costs).
	fctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), s.o.FetchTimeout)
	lat, lon := center(k)
	area, err := s.feed.Area(fctx, lat, lon, radiusNM(k))
	cancel()
	s.record(ctx, err)

	s.mu.Lock()
	defer s.mu.Unlock()
	c := s.cells[k]
	close(c.inflight)
	c.inflight = nil
	now := s.o.Now()
	if err != nil {
		s.failed(c, err, now)
		return s.served(c, now)
	}
	metrics.AircraftUpstream.WithLabelValues("ok").Inc()
	c.area, c.fetchedAt, c.failedAt = &area, now, time.Time{}
	if area.QuotaRemaining >= 0 {
		metrics.AircraftQuotaRemaining.Set(float64(area.QuotaRemaining))
		if area.QuotaRemaining <= s.o.Reserve {
			s.block(now, s.o.QuotaBackoff, "feed quota at the reserve")
		}
	}
	metrics.AircraftCells.WithLabelValues("fresh").Inc()
	return c.area
}

// record writes the result to Health, outside s.mu and detached from the
// viewer. A failure to record is logged, never served.
func (s *Service) record(ctx context.Context, fetchErr error) {
	if s.o.Health == nil {
		return
	}
	rctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 2*time.Second)
	defer cancel()
	now := s.o.Now()
	var err error
	if fetchErr == nil {
		err = s.o.Health.RecordSuccess(rctx, s.o.SourceID, now, domain.Validators{})
	} else {
		err = s.o.Health.RecordError(rctx, s.o.SourceID, now, fetchErr.Error())
	}
	if err != nil {
		s.o.Logger.Warn("record aircraft feed health", "err", err)
	}
}

// served is a cell's area when it cannot be fetched now: stale up to
// MaxStale, else nil. Caller holds s.mu.
func (s *Service) served(c *cell, now time.Time) *domain.AircraftArea {
	if c.area != nil && now.Sub(c.fetchedAt) <= s.o.MaxStale {
		metrics.AircraftCells.WithLabelValues("stale").Inc()
		return c.area
	}
	c.area = nil // too old to show: free it
	metrics.AircraftCells.WithLabelValues("missing").Inc()
	return nil
}

// failed records a feed error. Caller holds s.mu.
func (s *Service) failed(c *cell, err error, now time.Time) {
	var qe *domain.QuotaError
	if errors.As(err, &qe) {
		metrics.AircraftUpstream.WithLabelValues("quota").Inc()
		wait := qe.RetryAfter
		if wait <= 0 {
			wait = s.o.QuotaBackoff
		}
		s.block(now, wait, "feed answered 429")
		return
	}
	metrics.AircraftUpstream.WithLabelValues("error").Inc()
	c.failedAt = now
	s.o.Logger.Warn("aircraft feed failed", "err", err)
}

// block stops all feed requests until now+d. Caller holds s.mu.
func (s *Service) block(now time.Time, d time.Duration, why string) {
	if until := now.Add(d); until.After(s.blockedUntil) {
		s.blockedUntil = until
		s.o.Logger.Warn("aircraft feed paused", "reason", why, "until", until)
	}
}

// cells lists the grid cells bb touches; MinLon > MaxLon crosses the
// antimeridian.
func cells(bb domain.BBox, maxCells int) ([]cellKey, error) {
	type span struct{ lo, hi int }
	lats := span{latIndex(bb.MinLat), latIndex(bb.MaxLat)}
	lons := []span{{lonIndex(bb.MinLon), lonIndex(bb.MaxLon)}}
	if bb.MinLon > bb.MaxLon {
		lons = []span{{lonIndex(bb.MinLon), lonCells - 1}, {0, lonIndex(bb.MaxLon)}}
	}
	n := 0
	for _, l := range lons {
		n += (lats.hi - lats.lo + 1) * (l.hi - l.lo + 1)
	}
	if n > maxCells {
		return nil, ErrTooLarge
	}
	out := make([]cellKey, 0, n)
	for i := lats.lo; i <= lats.hi; i++ {
		for _, l := range lons {
			for j := l.lo; j <= l.hi; j++ {
				out = append(out, cellKey{i, j})
			}
		}
	}
	return out, nil
}

func latIndex(lat float64) int { return clamp(int(math.Floor((lat+90)/CellDegrees)), latCells-1) }
func lonIndex(lon float64) int { return clamp(int(math.Floor((lon+180)/CellDegrees)), lonCells-1) }

func clamp(i, hi int) int { return max(0, min(i, hi)) }

func center(k cellKey) (lat, lon float64) {
	return -90 + (float64(k.lat)+0.5)*CellDegrees, -180 + (float64(k.lon)+0.5)*CellDegrees
}

// radiusNM is the circle around a cell's center that holds all of it: the
// distance to its farthest corner, rounded up.
func radiusNM(k cellKey) int {
	lat, lon := center(k)
	h := CellDegrees / 2
	var far float64
	for _, dlat := range []float64{-h, h} {
		for _, dlon := range []float64{-h, h} {
			far = max(far, distanceNM(lat, lon, lat+dlat, lon+dlon))
		}
	}
	return int(math.Ceil(far))
}

// distanceNM is the great-circle distance in nautical miles.
func distanceNM(lat1, lon1, lat2, lon2 float64) float64 {
	const earthNM = 3440.065
	rad := math.Pi / 180
	dlat, dlon := (lat2-lat1)*rad, (lon2-lon1)*rad
	a := math.Sin(dlat/2)*math.Sin(dlat/2) + math.Cos(lat1*rad)*math.Cos(lat2*rad)*math.Sin(dlon/2)*math.Sin(dlon/2)
	return 2 * earthNM * math.Asin(math.Min(1, math.Sqrt(a)))
}

func inBox(bb domain.BBox, lon, lat float64) bool {
	if lat < bb.MinLat || lat > bb.MaxLat {
		return false
	}
	if bb.MinLon <= bb.MaxLon {
		return lon >= bb.MinLon && lon <= bb.MaxLon
	}
	return lon >= bb.MinLon || lon <= bb.MaxLon
}
